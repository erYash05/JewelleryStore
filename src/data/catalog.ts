export function getCollectionBySlug(slug: CollectionSlug): Collection {
  return COLLECTIONS.find((c) => c.slug === slug) ?? COLLECTIONS[0];
}

export function getProductsByCategory(slug: CollectionSlug): Product[] {
  return PRODUCTS.filter((p) => p.categorySlug === slug);
}

export function getProductByCode(code: string): Product {
  return (
    PRODUCTS.find((p) => p.code.toLowerCase() === code.toLowerCase()) ??
    PRODUCTS[0]
  );
}

export function getComplementaryProducts(currentCode: string): Product[] {
  const preferredCodes = ['SJ-BR-101', 'SJ-N-201', 'SJ-E-301', 'SJ-B-001'];
  const picks = preferredCodes
    .filter((code) => code !== currentCode)
    .slice(0, 3)
    .map((code) => getProductByCode(code));
  return picks;
}
